from __future__ import annotations

import re

import duckdb
import pytest
from conftest import edit_observations

from wbpipe.dashboard import fmt, fmt_pct, nice_ticks, run_dashboard, yoy_bin
from wbpipe.quality import run_checks
from wbpipe.report import ReportError


@pytest.fixture
def published(settings, pipeline):
    """Build, check and render; returns a function giving the dashboard HTML."""

    def _build(run_id: str = "run1") -> str:
        pipeline(run_id)
        run_checks(settings)
        return run_dashboard(settings).read_text()

    return _build


def test_dashboard_is_self_contained_and_complete(settings, published):
    page = published()
    # no external requests of any kind
    assert not re.search(r'(src|href)="(https?:)?//', page)
    assert "<link" not in page
    assert "Generated by <code>wbpipe</code> from ingest run <code>run1</code>" in page
    for name in (
        "Population, total",
        "GDP (current US$)",
        "Life expectancy at birth, total (years)",
    ):
        assert name in page
    assert page.count("<svg") == page.count("</svg>")
    assert page.count('class="chart"') == 4 * 3  # income lines, latest bars, YoY heatmaps
    assert "15/15 pass" in page
    assert "No missing values" in page
    assert page.count("<details>") == 3  # a data table behind every chart section


def test_dashboard_shows_missing_data_explicitly(settings, pipeline, fake_session):
    edit_observations(fake_session, "SP.POP.TOTL", lambda meta, rows: rows[-1].update(value=None))
    pipeline("run1")
    run_checks(settings)  # values_missing is only a warning
    page = run_dashboard(settings).read_text()
    assert "No missing values" not in page
    assert "null in source" in page and "gap in series" in page
    assert 'class="heat missing"' in page  # YoY cells that cannot be computed
    assert "1 warning(s)" in page
    assert "6/7" in page  # South Africa's population series


def test_source_text_is_escaped(settings, pipeline):
    pipeline("run1")
    with duckdb.connect(str(settings.paths.warehouse)) as con:
        con.execute(
            "UPDATE core.dim_country SET country_name = '<script>x</script>' "
            "WHERE country_iso3 = 'BRA'"
        )
    run_checks(settings)
    page = run_dashboard(settings).read_text()
    assert "<script>x</script>" not in page
    assert "&lt;script&gt;x&lt;/script&gt;" in page


def test_dashboard_requires_passing_checks(settings, pipeline):
    pipeline("run1")
    with pytest.raises(ReportError, match="has not been checked"):
        run_dashboard(settings)


def test_unchanged_data_renders_identically(settings, published):
    assert published() == run_dashboard(settings).read_text()


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        (1_450_935_791, "1.45B"),
        (29_298_013_000_000, "29.3T"),
        (86_169.66, "86.2K"),
        (79.3, "79.3"),
        (0, "0"),
        (-43_645_692_951.3, "-43.6B"),
        (None, "–"),
    ],
)
def test_compact_number_format(value, expected):
    assert fmt(value) == expected


def test_helpers():
    assert fmt_pct(-21.2) == "-21.20%" and fmt_pct(None) == "–"
    assert nice_ticks(0, 1.45e9) == [0, 5e8, 1e9, 1.5e9]
    assert [yoy_bin(p, 10) for p in (-9, -5, -2, 0.5, 2, 5, 9)] == [
        "d3",
        "d2",
        "d1",
        "n",
        "u1",
        "u2",
        "u3",
    ]
